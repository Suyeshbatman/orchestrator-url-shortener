package com.acme.orchestrator.agents.sdlc;

import com.acme.orchestrator.agents.llm.LlmClient;
import com.acme.orchestrator.agents.llm.PromptTemplates.Prompt;
import com.acme.orchestrator.agents.llm.UsageMeter;
import com.acme.orchestrator.agents.tools.Authorizer;
import com.acme.orchestrator.agents.tools.CodeIndexTool;
import com.acme.orchestrator.agents.tools.FileTool;
import com.acme.orchestrator.agents.tools.Workspace;
import com.acme.orchestrator.core.engine.Agent;
import com.acme.orchestrator.core.engine.AgentResult;
import com.acme.orchestrator.core.engine.ArtifactOutput;
import com.acme.orchestrator.core.engine.StageContext;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * The shape of an agent that asks the LLM for one structured artifact: gather inputs (each read is
 * recorded as lineage), render the agent's prompt template, get schema-valid JSON through {@link
 * LlmClient} (budget-charged, one repair attempt), and hand it back with the model and prompt hash.
 */
abstract class LlmAgent implements Agent {

  protected static final JsonMapper JSON = JsonMapper.builder().build();

  protected final AgentKit kit;
  private final String name;
  private final String outputType;
  private final int maxTokens;

  LlmAgent(AgentKit kit, String name, String outputType, int maxTokens) {
    this.kit = Objects.requireNonNull(kit, "kit");
    this.name = name;
    this.outputType = outputType;
    this.maxTokens = maxTokens;
  }

  /** Prompt values for this attempt; {@code product} and {@code feedback} are added. */
  protected abstract Map<String, String> inputs(StageContext ctx);

  /** One line for the audit log and approvers. */
  protected abstract String summary(JsonNode output);

  /** Checks the schema can't express; throw an AgentValidationException to retry with feedback. */
  protected void check(StageContext ctx, JsonNode output) {}

  /** Anything to record besides the artifact (e.g. the design's risk). */
  protected void after(StageContext ctx, JsonNode output) {}

  @Override
  public final AgentResult execute(StageContext ctx) {
    Map<String, String> values = new LinkedHashMap<>(inputs(ctx));
    values.put("product", kit.product());
    values.put("feedback", bullets(ctx.feedback(), "None (first attempt)."));
    Prompt prompt = kit.prompts().render(name, values);
    LlmClient.Structured out =
        kit.llm()
            .completeJson(
                UsageMeter.of(ctx),
                name,
                ctx.task().map(t -> t.id()),
                prompt,
                outputType,
                maxTokens);
    check(ctx, out.json());
    after(ctx, out.json());
    return AgentResult.success(
        summary(out.json()),
        new ArtifactOutput(
            outputType,
            JSON.writeValueAsString(out.json()),
            "generated by " + name + " from the recorded inputs",
            Optional.of(out.response().model()),
            Optional.of(out.promptHash())));
  }

  /**
   * What the target module looks like now (its map and its build file), in every mode: without it a
   * greenfield change invents its own packages and module layout.
   */
  protected static String codebase(StageContext ctx) {
    return ctx.tools()
        .find(Workspace.class)
        .map(w ->
            new CodeIndexTool(w.root(), TARGET_MODULE).index().toMarkdown()
                + "\n\n"
                + Patches.currentContent(
                    new FileTool(w, Authorizer.of(ctx)), List.of(TARGET_MODULE + "/pom.xml")))
        .orElse("Not available.");
  }

  /** The module every change is made in. */
  static final String TARGET_MODULE = "shortener-service";

  /** The content of an upstream artifact, recorded as an input. */
  protected static String content(StageContext ctx, String type) {
    return ctx.requireArtifact(type).contentJson();
  }

  protected static String bullets(List<String> items, String none) {
    return items.isEmpty() ? none : "- " + String.join("\n- ", items);
  }

  protected static int size(JsonNode node, String field) {
    JsonNode value = node.path(field);
    return value.isArray() ? value.size() : 0;
  }
}
